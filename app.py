import streamlit as st

# ??????? ?????? ??????? ??????
st.set_page_config(page_title="Smart Well Allocation Manager", layout="wide")

st.title("?? Smart Well Allocation Manager")
st.markdown("### ???? ????? ?????? ????? ?????? ????? - ??? ??? ?????")
st.write("---")

# --- ????? ?????? (G01-G44 ? GT01-GT09) ---
wells_g = [f"G{i:02d}" for i in range(1, 45)]
wells_gt = [f"GT{i:02d}" for i in range(1, 10)]
all_wells = wells_g + wells_gt

# --- ????? ?????: ?????? ??????? ??????? (Plant Target) ---
st.subheader("?? Surface Plant Targets")
col_g, col_c, col_w = st.columns(3)
with col_g:
    t_gas = st.number_input("Total Gas Target (m³/d)", value=1000000)
with col_c:
    t_cond = st.number_input("Total Condensate Target (m³/d)", value=250)
with col_w:
    t_water = st.number_input("Total Water Target (m³/d)", value=50)

st.write("---")

# --- ????? ??????: ??????? ?????? ---
st.subheader("??? Wells Configuration")
st.info("?? ?????? ???? ????? ??? OPEN ?????? ???????? ?????????? ????? ???????.")

open_wells_data = []

# ??? ?????? ??? ??? ???? ???? (Grid) ????? ????? ???????? ????????
well_cols = st.columns(4)  # ????? ????? ??? 4 ????? ??????

for idx, well in enumerate(all_wells):
    # ????? ?????? ??? ??????? ????????
    with well_cols[idx % 4]:
        with st.container():
            # ????? ??? ?????
            st.markdown(f"**Well: {well}**")
            status = st.selectbox(f"Status", ["CLOSED", "OPEN"], key=f"status_{well}")
            
            # ?????? ?????? JavaScript (???? ?????? ??? ??? ??? ????? ???????)
            if status == "OPEN":
                whp = st.number_input(f"WHP (psi)", min_value=0.0, value=1200.0, key=f"whp_{well}")
                choke = st.number_input(f"Choke (64th)", min_value=0.0, value=32.0, key=f"choke_{well}")
                
                # ?????? ?????? ???????? ?????? ?????
                predicted_gas = whp * choke * 0.4
                open_wells_data.append({"name": well, "pred_gas": predicted_gas, "status": "OPEN"})
                st.caption(f"Predicted: {predicted_gas:,.1f} m³/d")
            else:
                open_wells_data.append({"name": well, "pred_gas": 0.0, "status": "CLOSED"})
            st.markdown("---")

st.write("---")

# --- ????? ??????: ???? ???????? ???????? ??????? ---
if st.button("?? RUN ALLOCATION ENGINE", type="primary", use_container_width=True):
    st.subheader("?? Final Allocation Report")
    
    total_predicted_gas = sum(item['pred_gas'] for item in open_wells_data if item['status'] == 'OPEN')
    
    if total_predicted_gas > 0:
        factor = t_gas / total_predicted_gas
        
        # ????? ???? ??????? ???????
        report_data = []
        for item in open_wells_data:
            if item['status'] == 'OPEN':
                allocated = item['pred_gas'] * factor
                percentage = (allocated / t_gas) * 100
                report_data.append({
                    "Well Name": item['name'],
                    "Status": "?? OPEN",
                    "Allocated Gas (m³/d)": f"{allocated:,.2f}",
                    "Contribution %": f"{percentage:.2f}%"
                })
            else:
                report_data.append({
                    "Well Name": item['name'],
                    "Status": "?? CLOSED",
                    "Allocated Gas (m³/d)": "0.00",
                    "Contribution %": "0.00%"
                })
        
        # ??? ??????? ?? ???? ?????? ???? ????? ??
        st.dataframe(report_data, use_container_width=True)
    else:
        st.error("?? ?? ???? ???? ?????? (OPEN) ?? ???????? ??????? ??? ????? ?????? ????????.")